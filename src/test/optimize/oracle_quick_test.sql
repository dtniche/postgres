-- Oracle 数据库查询优化快速测试
-- 演示 EXISTS 子查询中 OR 条件的优化效果

-- 创建测试表
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE test_t1 CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE test_t2 CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE test_t1 (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a NUMBER,
    b NUMBER,
    data VARCHAR2(100)
);

CREATE TABLE test_t2 (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a NUMBER,
    b NUMBER,
    data VARCHAR2(100)
);

-- 插入测试数据
INSERT INTO test_t1 (a, b, data)
SELECT 
    ROUND(DBMS_RANDOM.VALUE(1, 1000)),
    ROUND(DBMS_RANDOM.VALUE(1, 1000)),
    'data_' || LEVEL
FROM DUAL
CONNECT BY LEVEL <= 5000;

INSERT INTO test_t2 (a, b, data)
SELECT 
    ROUND(DBMS_RANDOM.VALUE(1, 1000)),
    ROUND(DBMS_RANDOM.VALUE(1, 1000)),
    'data_' || LEVEL
FROM DUAL
CONNECT BY LEVEL <= 5000;

-- 创建索引
CREATE INDEX idx_test_t1_a ON test_t1(a);
CREATE INDEX idx_test_t1_b ON test_t1(b);
CREATE INDEX idx_test_t2_a ON test_t2(a);
CREATE INDEX idx_test_t2_b ON test_t2(b);

-- 更新统计信息
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'TEST_T1'); END;
/
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'TEST_T2'); END;
/

COMMIT;

-- 测试 1: 原始查询 (OR 条件在 EXISTS 中)
SET SERVEROUTPUT ON
PROMPT === 测试 1: 原始查询执行计划 ===
SET AUTOTRACE ON EXPLAIN STATISTICS

SELECT * FROM test_t1 WHERE
EXISTS (SELECT 1 FROM test_t2 WHERE test_t1.a = test_t2.a OR test_t1.b = test_t2.b);

SET AUTOTRACE OFF

-- 测试 2: 优化查询 (OR 条件分解)
PROMPT === 测试 2: 优化查询执行计划 ===
SET AUTOTRACE ON EXPLAIN STATISTICS

SELECT * FROM test_t1 WHERE
EXISTS (SELECT 1 FROM test_t2 WHERE test_t1.a = test_t2.a)
OR
EXISTS (SELECT 1 FROM test_t2 WHERE test_t1.b = test_t2.b);

SET AUTOTRACE OFF

-- 测试 3: 使用提示的优化查询
PROMPT === 测试 3: 使用提示的优化查询执行计划 ===
SET AUTOTRACE ON EXPLAIN STATISTICS

SELECT /*+ USE_HASH(test_t1, test_t2) */ * FROM test_t1 WHERE
EXISTS (SELECT 1 FROM test_t2 WHERE test_t1.a = test_t2.a OR test_t1.b = test_t2.b);

SET AUTOTRACE OFF

