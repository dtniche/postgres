-- Oracle: OR-Expansion -> EXISTS -> Subquery Unnesting 演示

SET SERVEROUTPUT ON

-- 一、准备数据
BEGIN EXECUTE IMMEDIATE 'DROP TABLE T1 CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE T2 CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE T3 CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE T1 (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  A  NUMBER,
  B  NUMBER,
  PAYLOAD VARCHAR2(50)
);

CREATE TABLE T2 (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  A  NUMBER
);

CREATE TABLE T3 (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  B  NUMBER
);

INSERT INTO T1(A,B,PAYLOAD)
SELECT ROUND(DBMS_RANDOM.VALUE(0,2000)), ROUND(DBMS_RANDOM.VALUE(0,2000)), 'p'||LEVEL
FROM DUAL CONNECT BY LEVEL <= 200000;

INSERT INTO T2(A)
SELECT ROUND(DBMS_RANDOM.VALUE(0,2000))
FROM DUAL CONNECT BY LEVEL <= 200000;

INSERT INTO T3(B)
SELECT ROUND(DBMS_RANDOM.VALUE(0,2000))
FROM DUAL CONNECT BY LEVEL <= 200000;

CREATE INDEX IDX_T1_A ON T1(A);
CREATE INDEX IDX_T1_B ON T1(B);
CREATE INDEX IDX_T2_A ON T2(A);
CREATE INDEX IDX_T3_B ON T3(B);

BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'T1'); END;
/
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'T2'); END;
/
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'T3'); END;
/
COMMIT;

ALTER SESSION SET STATISTICS_LEVEL = ALL;

-- 二、OR 展开前（单 EXISTS + OR）
PROMPT === 原始：单 EXISTS 内含 OR ===
SELECT COUNT(*) FROM (
  SELECT * FROM T1 WHERE EXISTS (
    SELECT 1 FROM T2 WHERE T1.A = T2.A
    UNION ALL
    SELECT 1 FROM T3 WHERE T1.B = T3.B
  )
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

-- 三、OR 展开后（两个 EXISTS）
PROMPT === OR 展开：两个 EXISTS ===
SELECT COUNT(*) FROM (
  SELECT * FROM T1
  WHERE EXISTS (SELECT 1 FROM T2 WHERE T1.A = T2.A)
     OR EXISTS (SELECT 1 FROM T3 WHERE T1.B = T3.B)
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

-- 四、子查询提升（UNNEST/GROUP BY + JOIN 等价重写）
PROMPT === 子查询提升：GROUP BY + LEFT JOIN 计数判定 ===
SELECT COUNT(*) FROM (
  SELECT T1.*
  FROM T1
  LEFT JOIN (
    SELECT A, COUNT(*) C1 FROM T2 GROUP BY A
  ) TT2 ON T1.A = TT2.A
  LEFT JOIN (
    SELECT B, COUNT(*) C2 FROM T3 GROUP BY B
  ) TT3 ON T1.B = TT3.B
  WHERE TT2.C1 IS NOT NULL OR TT3.C2 IS NOT NULL
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

