-- Oracle: Correlated subquery unnesting demo
-- 将相关标量子查询 + 聚合改写为 GROUP BY + JOIN，对比实际执行计划

SET SERVEROUTPUT ON

-- 1. 准备数据
BEGIN EXECUTE IMMEDIATE 'DROP TABLE T1 CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE T2 CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE T1 (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  C  NUMBER,
  A  NUMBER
);

CREATE TABLE T2 (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  C  NUMBER,
  B  NUMBER
);

INSERT INTO T1(C, A)
SELECT ROUND(DBMS_RANDOM.VALUE(0, 1000)), ROUND(DBMS_RANDOM.VALUE(0, 100), 2)
FROM DUAL CONNECT BY LEVEL <= 100000;

INSERT INTO T2(C, B)
SELECT ROUND(DBMS_RANDOM.VALUE(0, 1000)), ROUND(DBMS_RANDOM.VALUE(0, 100), 2)
FROM DUAL CONNECT BY LEVEL <= 300000;

CREATE INDEX IDX_T1_C ON T1(C);
CREATE INDEX IDX_T2_C ON T2(C);

BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'T1'); END;
/
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'T2'); END;
/
COMMIT;

ALTER SESSION SET STATISTICS_LEVEL = ALL;

-- 2. 原始写法：相关标量子查询 + 聚合
PROMPT === 原始：相关子查询 ===
SELECT COUNT(*) FROM (
  SELECT *
  FROM T1
  WHERE T1.A > 1.2 * (SELECT AVG(T2.B) FROM T2 WHERE T2.C = T1.C)
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

-- 3. 改写写法：先聚合再 JOIN（便于触发 HASH JOIN）
PROMPT === 改写：GROUP BY + JOIN ===
SELECT COUNT(*) FROM (
  SELECT T1.*
  FROM T1
  JOIN (
    SELECT C, AVG(B) AS AVG_B
    FROM T2
    GROUP BY C
  ) G ON G.C = T1.C
  WHERE T1.A > 1.2 * G.AVG_B
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

-- 4. 可选：用 Hint 强制展开/连接方式
PROMPT === 使用提示：UNNEST + USE_HASH ===
SELECT COUNT(*) FROM (
  SELECT /*+ UNNEST */ *
  FROM T1
  WHERE T1.A > 1.2 * (
    SELECT /*+ USE_HASH(T2) */ AVG(T2.B) FROM T2 WHERE T2.C = T1.C
  )
);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

