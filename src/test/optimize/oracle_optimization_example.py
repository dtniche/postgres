    def __init__(self, host: str = '172.23.160.1', port: int = 1521, 
                 service_name: str = 'XEPDB1', user: str = 'sys', password: str = '111111'):
        """初始化 Oracle 连接参数"""
        self.host = host
        self.port = port
        self.service_name = service_name
        self.user = user
        self.password = password
        self.connection = None
    
    def connect(self) -> bool:
        """连接 Oracle 数据库"""
        try:
            dsn = cx_Oracle.makedsn(self.host, self.port, service_name=self.service_name)
            self.connection = cx_Oracle.connect(self.user, self.password, dsn, mode=cx_Oracle.SYSDBA)
            print("✅ Oracle 连接成功")
            return True
        except Exception as e:
            print(f"❌ Oracle 连接失败: {e}")
            return False
    
    def execute_sql(self, sql: str, fetch_all: bool = True) -> Tuple[bool, List, str]:
        """执行 SQL 语句并返回结果"""
        if not self.connection:
            return False, [], "未连接到数据库"
        
        cursor = self.connection.cursor()
        try:
            cursor.execute(sql)
            if fetch_all:
                rows = cursor.fetchall()
                return True, rows, ""
            else:
                return True, [], ""
        except Exception as e:
            return False, [], str(e)
        finally:
            cursor.close()
    
