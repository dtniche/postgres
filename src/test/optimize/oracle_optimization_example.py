    def get_execution_plan(self, sql: str, query_name: str) -> Dict:
        """获取执行计划"""
        print(f"\n分析查询: {query_name}")
        print("-" * 60)
        
        # 启用执行计划收集
        self.execute_sql("ALTER SESSION SET STATISTICS_LEVEL = ALL", fetch_all=False)
        
        # 执行查询
        start_time = time.time()
        success, rows, error = self.execute_sql(sql)
        execution_time = (time.time() - start_time) * 1000  # 转换为毫秒
        
        if not success:
            print(f"❌ 查询执行失败: {error}")
            return {}
        
        # 获取执行计划
        plan_sql = """
        SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'))
        """
        
        success, plan_rows, error = self.execute_sql(plan_sql)
        if not success:
            print(f"❌ 获取执行计划失败: {error}")
            return {}
        
        # 分析执行计划
        plan_text = '\n'.join([row[0] for row in plan_rows])
        print("执行计划:")
        print(plan_text)
        
        # 提取关键信息
        analysis = {
            'query_name': query_name,
            'execution_time_ms': execution_time,
            'rows_returned': len(rows),
            'plan_text': plan_text,
            'has_nested_loop': 'NESTED LOOPS' in plan_text.upper(),
            'has_hash_join': 'HASH JOIN' in plan_text.upper(),
            'has_index_scan': 'INDEX' in plan_text.upper(),
            'has_table_scan': 'TABLE ACCESS FULL' in plan_text.upper(),
            'has_union_all': 'UNION-ALL' in plan_text.upper(),
            'has_or_expansion': 'VW_ORE_' in plan_text.upper()
        }
        
        print(f"执行时间: {analysis['execution_time_ms']:.2f} ms")
        print(f"返回行数: {analysis['rows_returned']:,}")
        print(f"包含嵌套循环: {analysis['has_nested_loop']}")
        print(f"包含哈希连接: {analysis['has_hash_join']}")
        print(f"包含索引扫描: {analysis['has_index_scan']}")
        print(f"包含全表扫描: {analysis['has_table_scan']}")
        print(f"包含 UNION-ALL: {analysis['has_union_all']}")
        print(f"包含 OR 扩展: {analysis['has_or_expansion']}")
        
        return analysis
    
    def run_optimization_comparison(self) -> Dict:
        """运行优化对比测试"""
        print("\n" + "="*80)
        print("Oracle 查询优化对比测试")
        print("="*80)
        
        # 定义测试查询
        queries = {
            "原始查询 (OR 条件在 EXISTS 中)": """
                SELECT c.customer_id, c.name, c.email
                FROM customers c
                WHERE EXISTS (
                    SELECT 1 FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE o.customer_id = c.customer_id 
                    AND (p.category = 'Electronics' OR p.price > 500)
                )
            """,
            
            "优化查询 (OR 条件分解)": """
                SELECT c.customer_id, c.name, c.email
                FROM customers c
                WHERE EXISTS (
                    SELECT 1 FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE o.customer_id = c.customer_id 
                    AND p.category = 'Electronics'
                )
                OR EXISTS (
                    SELECT 1 FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE o.customer_id = c.customer_id 
                    AND p.price > 500
                )
            """,
            
            "使用提示的优化查询": """
                SELECT /*+ USE_HASH(c, o, p) */ c.customer_id, c.name, c.email
                FROM customers c
                WHERE EXISTS (
                    SELECT 1 FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE o.customer_id = c.customer_id 
                    AND (p.category = 'Electronics' OR p.price > 500)
                )
            """,
            
            "进一步优化 (使用 UNION)": """
                SELECT DISTINCT c.customer_id, c.name, c.email
                FROM customers c
                WHERE c.customer_id IN (
                    SELECT o.customer_id FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE p.category = 'Electronics'
                    UNION
                    SELECT o.customer_id FROM orders o 
                    JOIN products p ON o.product_id = p.product_id
                    WHERE p.price > 500
                )
            """
        }
        
        results = {}
        
        for query_name, sql in queries.items():
            results[query_name] = self.get_execution_plan(sql, query_name)
            time.sleep(1)  # 避免缓存影响
        
        return results
    
